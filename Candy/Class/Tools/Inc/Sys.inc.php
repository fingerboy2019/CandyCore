<?php
/**
 * sys 系统配置（框架默认值）
 *
 * 这是「sys 系统级配置」的容器：按业务分组，每组一个子数组。
 * 目前只有 security（/sys/* 端点的访问控制），后续可继续加 log / upload / notify 等分组。
 *
 * 项目改过的值请写 Source/Inc/Sys.inc.php（与本文件深合并，键以本文件为准）；
 * 页面上可编辑：/sys/config → Sys；名单与模式：/sys/ip；命令行：php candy ip ...
 *
 * @package Candy\Extend\Tools\Endpoint
 */
return [
    /* ---------------------------------------------------------------------
     * 运行时标识（开发 / 调试模式）
     *
     * 以前写在 Source/Inc/Init.inc.php 里硬编码，切换要改代码；
     * 现在由框架在 Bootstrap::boot() 早期定义常量，改这里（或 .env）即可生效。
     * 优先级：.env 的 APP_DEBUG / APP_DEV > 本配置 > 默认 false
     *
     *   debug：调试模式（调试条、详细报错、禁止缓存）
     *   dev  ：开发模式（文件热更新 / FileMonitor）
     * ------------------------------------------------------------------- */
    'runtime' => [
        'debug' => false,
        'dev'   => false,
    ],

    /* ---------------------------------------------------------------------
     * 安全（/sys/* 端点的 IP 防护）
     *
     *   mode=blacklist：命中黑名单 → 403（默认）
     *   mode=whitelist：不在白名单 → 403（切换时会自动放行当前 IP，避免自锁）
     * ------------------------------------------------------------------- */
    'security' => [
        /* -----------------------------------------------------------------
         * 端点访问令牌（/sys/* 用）
         *
         *   token  ：全局令牌。默认 'candy-sys'，正式使用请在
         *            项目覆盖 Source/Inc/Sys.inc.php（或 /sys/config）里改成自己的值
         *   tokens ：按端点覆盖（键=端点路径，如 'sys/ip'），优先级高于 token
         * ----------------------------------------------------------------- */
        'token'  => 'candy-sys',
        'tokens' => [],

        'ip_guard' => [
            'enable'   => true,
            'mode'     => 'blacklist',   // blacklist | whitelist
            'max_fail' => 3,             // 窗口内允许的错误次数
            'window'   => 600,           // 计数窗口（秒）
            'ban_time' => 7200,          // 封禁时长（秒）

            // 豁免回环地址（127.0.0.1 / ::1）。默认关：
            // 若站点在 nginx 后面且没透传真实 IP，PHP 看到的所有来源都是 127.0.0.1，
            // 开了等于整个防护失效 —— 只有确定「PHP 直接对外」的单机部署才开。
            'trust_local' => false,

            // 静态豁免列表（不管哪种模式都直接放行，且不计数、不封禁）
            // 运行期增删请用 /sys/ip 页面或 php candy ip add <ip> --type=w
            'allow' => [],
        ],
    ],
];
